#!/usr/bin/env python3
"""
Generate a fully pinned requirements file for bug-fix branches.

Resolves all transient dependencies from pyproject.toml dependency-groups
and writes ci/fully-pinned-requirements.txt with hashes.

Usage:
    python ci/generate_fully_pinned.py          # generate for main
    python ci/generate_fully_pinned.py --check  # CI: fail if out of date

This implements https://github.com/matplotlib/matplotlib/issues/23548
- On main, ci/fully-pinned-requirements.txt is the source of truth
- On branching (e.g. v3.10.x), it is renamed to ci/fully-pinned-v3.10.x.txt
  and used exclusively for tests on that bug-fix branch.
"""
